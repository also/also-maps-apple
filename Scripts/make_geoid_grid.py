#!/usr/bin/env python3
"""Writes Sources/Routes/GeoidGrid.swift: EGM96 geoid heights on a coarse
grid, for turning GPX heights (above mean sea level) into heights above the
WGS84 ellipsoid.

Input: GeographicLib's egm96-15.pgm (EGM96 on a 15-minute grid), from
https://sourceforge.net/projects/geographiclib/files/geoids-distrib/egm96-15.tar.bz2
EGM96 is the US National Geospatial-Intelligence Agency's model, a US
government work in the public domain.

Usage: Scripts/make_geoid_grid.py path/to/egm96-15.pgm [step-degrees]

Prints how far bilinear interpolation on the coarse grid strays from the
15-minute grid at every 15-minute point.
"""
import base64
import struct
import sys

def read_pgm(path):
    data = open(path, "rb").read()
    tokens, offset, scale, pos = [], -108.0, 0.003, 0
    while len(tokens) < 4:
        end = data.index(b"\n", pos)
        line, pos = data[pos:end], end + 1
        if line.startswith(b"#"):
            words = line[1:].split()
            if len(words) == 2 and words[0] == b"Offset":
                offset = float(words[1])
            if len(words) == 2 and words[0] == b"Scale":
                scale = float(words[1])
            continue
        tokens += line.split()
    assert tokens[0] == b"P5"
    width, height = int(tokens[1]), int(tokens[2])
    raw = struct.unpack(">%dH" % (width * height), data[pos:pos + 2 * width * height])
    # Rows from 90°N to 90°S, columns eastward from 0°E, every 15 minutes.
    return width, height, [offset + scale * r for r in raw]

def main():
    path = sys.argv[1]
    step = float(sys.argv[2]) if len(sys.argv) > 2 else 2.0
    width, height, full = read_pgm(path)
    k = round(step / 0.25)
    rows, columns = (height - 1) // k + 1, width // k
    grid = [full[(r * k) * width + c * k] for r in range(rows) for c in range(columns)]
    decimetres = [round(v * 10) for v in grid]
    packed = struct.pack("<%dh" % len(decimetres), *decimetres)
    text = base64.b64encode(packed).decode()

    def coarse(lat, lon):
        y, x = (90 - lat) / step, (lon % 360) / step
        y0 = min(int(y), rows - 2); x0 = int(x) % columns
        fy, fx = y - y0, x - int(x)
        x1 = (x0 + 1) % columns
        g = lambda r, c: decimetres[r * columns + c] / 10
        return ((g(y0, x0) * (1 - fx) + g(y0, x1) * fx) * (1 - fy)
                + (g(y0 + 1, x0) * (1 - fx) + g(y0 + 1, x1) * fx) * fy)

    errors = sorted(abs(coarse(90 - r * 0.25, c * 0.25) - full[r * width + c])
                    for r in range(height) for c in range(width))
    rms = (sum(e * e for e in errors) / len(errors)) ** 0.5
    p99 = errors[int(0.99 * len(errors))]
    print(f"{rows}×{columns} grid; bilinear vs 15′: RMS {rms:.2f} m, 99% within {p99:.2f} m, worst {errors[-1]:.2f} m",
          file=sys.stderr)

    lines = [text[i:i + 100] for i in range(0, len(text), 100)]
    body = "\n".join("        " + line for line in lines)
    swift = f'''// Generated by Scripts/make_geoid_grid.py; don't edit.
//
// EGM96 geoid heights (NGA; US government work, public domain), taken every
// {step:g}° from GeographicLib's 15-minute egm96-15.pgm. Bilinear
// interpolation on this grid is within {p99:.1f} m of the 15-minute grid at 99%
// of its points (RMS {rms:.2f} m, worst {errors[-1]:.0f} m, near deep trenches and
// steep mountain fronts).

extension Geoid {{
    /// Degrees between grid points.
    static let gridStep: Double = {step:g}
    /// {rows} rows from 90°N to 90°S, each {columns} columns eastward from 0°E.
    static let gridRows = {rows}
    static let gridColumns = {columns}
    /// Little-endian Int16 decimetres, row by row, as base64.
    static let gridBase64 = """
{body}
        """
}}
'''
    sys.stdout.write(swift)

main()
